#!/usr/bin/env python3
"""Builds docs/FEATURES.md and the beta block of ROADMAP.md from features/*.toml.

    python3 scripts/features.py          write both
    python3 scripts/features.py --check  exit 1 if either is out of date (CI runs this)
"""
import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEATURES = ROOT / "docs" / "FEATURES.md"
ROADMAP = ROOT / "ROADMAP.md"
BEGIN = "<!-- Generated by scripts/features.py from features/*.toml; edit those, not this block. -->"
END = "<!-- End of the generated block. -->"
ISSUES = "https://github.com/JackMechem/marbble/issues"

STATUSES = ("done", "partial", "missing")
TIERS = ("core", "pro", "advanced", "studio", "content", "platform")
FIELDS = {"section", "name", "status", "tier", "beta", "logic", "issue", "note"}
MARK = {"done": "✓", "partial": "◐", "missing": "○"}


def load():
    """The areas in their order, each with its features; stops at the first malformed entry."""
    areas = []
    for path in sorted((ROOT / "features").glob("*.toml")):
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        seen = set()
        for f in data["feature"]:
            where = f"{path.name}: {f.get('name', '?')!r}"
            if extra := set(f) - FIELDS:
                sys.exit(f"{where} has unknown fields {sorted(extra)}")
            if not {"section", "name", "status", "tier"} <= set(f):
                sys.exit(f"{where} needs section, name, status and tier")
            if f["status"] not in STATUSES or f["tier"] not in TIERS:
                sys.exit(f"{where}: status must be one of {STATUSES} and tier one of {TIERS}")
            if (f["section"], f["name"]) in seen:
                sys.exit(f"{where} is listed twice in {f['section']!r}")
            seen.add((f["section"], f["name"]))
        areas.append({"file": path.name, **data})
    return sorted(areas, key=lambda a: a["order"])


def counts(features):
    c = Counter(f["status"] for f in features)
    return c["done"], c["partial"], c["missing"]


def beta_left(features):
    return [f for f in features if f.get("beta") and f["status"] != "done"]


def item(f, beta_tag=True):
    """One feature as a list line: mark, name, issue, note."""
    line = f"- {MARK[f['status']]} {f['name']}"
    if f.get("issue"):
        line += f" ([#{f['issue']}]({ISSUES}/{f['issue']}))"
    if f.get("note") and f["status"] != "done":
        line += f": {f['note']}"
    if beta_tag and f.get("beta") and f["status"] != "done":
        line += " **Beta.**"
    return line


def summary_table(areas):
    rows = ["| Area | Done | Partial | Missing | Share done |", "|---|---:|---:|---:|---:|"]
    for a in areas:
        done, partial, missing = counts(a["feature"])
        share = round(100 * done / len(a["feature"]))
        rows.append(f"| [{a['title']}](#{slug(a['title'])}) | {done} | {partial} | {missing} | {share}% |")
    return rows


def slug(title):
    return "".join(c for c in title.lower().replace(" ", "-") if c.isalnum() or c == "-")


def features_md(areas):
    every = [f for a in areas for f in a["feature"]]
    done, partial, missing = counts(every)
    beta = [f for f in every if f.get("beta")]
    out = [
        "# Feature list",
        "",
        "Every feature of Logic Pro, by area, and how far Marbble has it. This page is generated by",
        "`scripts/features.py` from the files in `features/`: change those, in the pull request that",
        "changes the feature. [ROADMAP.md](../ROADMAP.md) says what beta needs and what's being worked on.",
        "",
        f"Marbble has **{done}** of {len(every)} features, and a simpler version of {partial} more; "
        f"{missing} are missing. Beta needs {len(beta)} of them, and {len(beta_left(every))} of those are still to do.",
        "",
        "✓ done · ◐ partial: the note says what's missing · ○ missing · **Beta.** needed for beta and not done yet",
        "",
        *summary_table(areas),
    ]
    for a in areas:
        a_done = counts(a["feature"])[0]
        out += ["", f"## {a['title']}", "", f"{a['about']} {a_done} of {len(a['feature'])} done."]
        sections = list(dict.fromkeys(f["section"] for f in a["feature"]))
        for s in sections:
            fs = [f for f in a["feature"] if f["section"] == s]
            out += ["", f"### {s}", "", f"{counts(fs)[0]} of {len(fs)} done.", ""]
            out += [item(f) for f in sorted(fs, key=lambda f: STATUSES.index(f["status"]))]
    return "\n".join(out) + "\n"


def roadmap_block(areas):
    every = [f for a in areas for f in a["feature"]]
    beta = [f for f in every if f.get("beta")]
    done, partial, missing = counts(beta)
    out = [
        BEGIN,
        "",
        f"Beta needs **{len(beta)}** features: **{done}** are done, {partial} are partial and {missing} are missing.",
        "The table counts only those beta features, by area.",
        "",
        "| Area | Beta features | Done | Partial | Missing | Left for beta |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for a in areas:
        b = [f for f in a["feature"] if f.get("beta")]
        if b:
            d, p, m = counts(b)
            out.append(f"| {a['title']} | {len(b)} | {d} | {p} | {m} | {len(beta_left(b))} |")
    out += ["", "What's left for beta, by area (◐ partial, ○ missing):"]
    for a in areas:
        left = beta_left(a["feature"])
        if left:
            out += ["", f"**{a['title']}**", ""] + [item(f, beta_tag=False) for f in left]
    return "\n".join(out + ["", END])


def with_block(text, block):
    head, _, rest = text.partition(BEGIN)
    _, found, tail = rest.partition(END)
    if not found:
        sys.exit(f"ROADMAP.md needs the generated block's markers:\n{BEGIN}\n{END}")
    return head + block + tail


def main():
    areas = load()
    want = {FEATURES: features_md(areas), ROADMAP: with_block(ROADMAP.read_text(encoding="utf-8"), roadmap_block(areas))}
    stale = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        if stale:
            sys.exit("Out of date: " + ", ".join(p.name for p in stale) + ". Run python3 scripts/features.py.")
        return
    for p in stale:
        p.write_text(want[p], encoding="utf-8")
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
